export type Language = 'en' | 'te';

/**
 * Maps dynamic data to translations if available
 */
export const translateData = (data: string, lang: Language): string => {
    if (lang === 'en') return data;

    // Simple key mapping for categories
    const key = `cat_${data.replace(/\s+/g, '_')}` as keyof typeof translations.te;
    return translations.te[key] || data;
};
